#!/usr/bin/env node
// Generates src/lucide.js (every Lucide icon, inner SVG markup only) from the lucide-static
// dev dependency, and copies its licence to third-party/. Run after bumping lucide-static:
//   npm run build:icons
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const pkg = path.join(root, 'node_modules/lucide-static');
const dir = path.join(pkg, 'icons');
const icons = {};
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.svg')).sort()) {
  const m = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(fs.readFileSync(path.join(dir, f), 'utf8'));
  icons[f.slice(0, -4)] = m[1].replace(/\s+/g, ' ').replace(/>\s+</g, '><').trim();
}
const version = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version;
const out = `// Generated by tools/build-icons.js from lucide-static ${version} (ISC licence, see third-party/lucide-LICENSE).\n` +
  `// Each value is the inside of a 24x24 SVG: stroke-drawn, no fill. Do not edit.\n` +
  `const LUCIDE = ${JSON.stringify(icons)};\n` +
  `if (typeof module !== 'undefined') module.exports = LUCIDE;\n`;
fs.writeFileSync(path.join(root, 'src/lucide.js'), out);
fs.mkdirSync(path.join(root, 'third-party'), { recursive: true });
fs.copyFileSync(path.join(pkg, 'LICENSE'), path.join(root, 'third-party/lucide-LICENSE'));
console.log(`src/lucide.js: ${Object.keys(icons).length} icons, ${Math.round(out.length / 1024)} KB (lucide-static ${version})`);
