#!/usr/bin/env node
// Generates the icon data from the lucide-static dev dependency and copies its licence:
//   src/lucide-core.js   the drawings of the icons Trace names itself (small, bundled in every page)
//   src/lucide-names.js  every Lucide icon name (validation and "did you mean"; bundled in every page)
//   src/lucide.js        every drawing (loaded by Node only, when a diagram uses an icon outside the core)
// Pages fetch the drawing of any other icon from jsDelivr when a diagram first uses it.
// Run after bumping lucide-static:  npm run build:icons
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const pkg = path.join(root, 'node_modules/lucide-static');
const dir = path.join(pkg, 'icons');
// the Lucide icons behind the names in ICON_ALIASES (src/trace.js) and the names that equal Lucide's
const CORE = ['database', 'server', 'user', 'cloud', 'app-window', 'list-end', 'brick-wall-fire', 'archive', 'graph-hub',
  'container', 'webhook', 'lock', 'smartphone', 'globe', 'router', 'ethernet-port', 'wifi', 'shield-check', 'network',
  'shield', 'laptop', 'monitor', 'printer', 'cctv', 'zap', 'square-function', 'clock', 'file-text', 'bell', 'chart-column',
  'settings', 'mail', 'key-round'];
const icons = {};
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.svg')).sort()) {
  const m = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(fs.readFileSync(path.join(dir, f), 'utf8'));
  icons[f.slice(0, -4)] = m[1].replace(/\s+/g, ' ').replace(/>\s+</g, '><').trim();
}
const version = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version;
const head = `// Generated by tools/build-icons.js from lucide-static ${version} (ISC licence, see third-party/lucide-LICENSE). Do not edit.\n`;
const write = (file, name, value) => fs.writeFileSync(path.join(root, 'src', file),
  head + `const ${name} = ${JSON.stringify(value)};\nif (typeof module !== 'undefined') module.exports = ${name};\n`);
const missing = CORE.filter(n => !icons[n]);
if (missing.length) { console.error('Not in lucide-static: ' + missing.join(', ')); process.exit(1); }
write('lucide-core.js', 'LUCIDE_CORE', Object.fromEntries(CORE.map(n => [n, icons[n]])));
write('lucide-names.js', 'LUCIDE_NAMES', Object.keys(icons));
write('lucide.js', 'LUCIDE', icons);
fs.mkdirSync(path.join(root, 'third-party'), { recursive: true });
fs.copyFileSync(path.join(pkg, 'LICENSE'), path.join(root, 'third-party/lucide-LICENSE'));
const kb = f => Math.round(fs.statSync(path.join(root, 'src', f)).size / 1024);
console.log(`lucide-static ${version}: core ${CORE.length} icons ${kb('lucide-core.js')} KB, names ${Object.keys(icons).length} ${kb('lucide-names.js')} KB, full set ${kb('lucide.js')} KB (Node only)`);
